"""Generate the mobile snapshot from the reviewed web course pack."""
import argparse,json,re,uuid
from pathlib import Path
root=Path(__file__).resolve().parents[2]
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('pack',type=Path,help='검토한 course-pack JSON 경로')
parser.add_argument('--output',type=Path,default=root/'shared/src/commonMain/kotlin/com/example/study_helper/study/MobileStudyGuides.kt')
args=parser.parse_args()
pack=json.loads(args.pack.read_text())
def string(s):return json.dumps(s,ensure_ascii=False).replace('$','\\$')
rows=[]
for index,g in enumerate(pack['guides'],1):
 note=str(uuid.uuid5(uuid.NAMESPACE_URL,g['key']+'/note'));quiz=str(uuid.uuid5(uuid.NAMESPACE_URL,g['key']+'/quiz'))
 def link(m):
  n,page=m.group(1),m.group(2)
  return f'[자료 {n}'+(f' · PDF {page}쪽' if page else '')+f'](study-source://{index}/{n}?page={page or 1})'
 body=re.sub(r'\(자료 (\d+)(?: · PDF (\d+)쪽)?\)',link,g['summary'])
 paths=[p.removeprefix('학습/') for p in g['sources']]
 body+='\n\n## 원본 자료\n\n'+'\n'.join(f'- [자료 {i+1} · {p.rsplit("/",1)[-1]}](study-source://{index}/{i+1}?page=1)' for i,p in enumerate(paths))+'\n\n원본은 공부 폴더 공유에서 같은 Drive 폴더를 동기화한 뒤 열 수 있습니다.\n'
 q=dict(g['quiz'],sourceNoteId=note)
 path=f'{g["subject"]}/{g["unit"]}/수업 통합 정리.md'
 rows.append('        MobileStudyGuide('+', '.join(string(x) for x in [note,quiz,g['title'],body,json.dumps(q,ensure_ascii=False,separators=(',',':')),path])+', listOf('+', '.join(string(p) for p in paths)+'))')
content='''// Generated by tools/course-guides/generate_mobile.py. Edit the source course pack instead.
package com.example.study_helper.study

data class MobileStudyGuide(val noteId: String, val quizId: String, val title: String,
    val body: String, val quizJson: String, val path: String, val sources: List<String>)

object MobileStudyGuides {
    val all: List<MobileStudyGuide> = listOf(
'''+',\n'.join(rows)+'''
    )
    fun path(id: String): String = all.firstOrNull { it.noteId == id || it.quizId == id }?.path.orEmpty()
    fun isGuide(id: String?): Boolean = all.any { it.noteId == id }
    fun source(url: String): Pair<String, Int>? {
        val match = Regex("study-source://([0-9]+)/([0-9]+)\\\\?page=([0-9]+)").matchEntire(url) ?: return null
        val guide = match.groupValues[1].toIntOrNull()?.let { all.getOrNull(it - 1) } ?: return null
        val path = match.groupValues[2].toIntOrNull()?.let { guide.sources.getOrNull(it - 1) } ?: return null
        val page = match.groupValues[3].toIntOrNull()?.takeIf { it in 1..10000 } ?: return null
        return path to page
    }
}
'''
args.output.write_text(content)
print('Generated',len(rows),'mobile guides')
